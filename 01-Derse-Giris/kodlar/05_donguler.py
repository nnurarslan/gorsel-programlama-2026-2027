# for ve while döngüleri

print("1) for döngüsü")
for sayi in range(1, 6):
    print("Sayı:", sayi)

print("\n2) Liste üzerinde döngü")
dersler = ["Python", "OOP", "Qt Designer", "PyQt"]

for ders in dersler:
    print(ders)

print("\n3) while döngüsü")
sayac = 3

while sayac > 0:
    print(sayac)
    sayac -= 1

print("Başlıyoruz!")
